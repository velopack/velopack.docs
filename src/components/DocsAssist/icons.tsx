import React from "react";

// Two families, deliberately:
// - Anything with substance (notices, example questions, actions) uses solid icons from one pack,
//   Icons8 "Windows 11 Filled" (fluent-systems-filled, 48px grid), inlined with fill="currentColor".
//   The Icons8 id of each is noted next to it.
// - Trivial controls (chevrons, arrows, expand/collapse, external link) are clean hand-drawn strokes.

type IconProps = { size?: number; className?: string };

function Solid({ d, size = 16, className }: IconProps & { d: string }) {
  return (
    <svg className={className} viewBox="0 0 48 48" width={size} height={size} fill="currentColor" aria-hidden="true" focusable="false">
      <path d={d} />
    </svg>
  );
}

function Stroke({ children, size = 16, className, width = 1.75 }: IconProps & { children: React.ReactNode; width?: number }) {
  return (
    <svg
      className={className}
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={width}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

